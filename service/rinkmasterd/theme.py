"""Cabinet theme management: EmulationStation themes and Attract-Mode layouts.

Installs and activates themes on RetroPie cabinets:
- EmulationStation: themes in `<configs>/all/emulationstation/themes/<theme>`,
  active theme configured as `<string name="ThemeSet" value="<theme>" />` in `es_settings.cfg`.
- Attract-Mode: layouts in `<configs>/all/attractmode/layouts/<layout>`,
  active layout configured as `layout <layout>` in `attract.cfg`.
"""
from __future__ import annotations

import io
import os
import re
import shutil
import tarfile
import zipfile
from typing import List, Optional, Tuple

THEME_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._\-]*$")
MAX_THEME_NAME_LEN = 64
MAX_ARCHIVE_BYTES = 16 * 1024 * 1024  # 16 MB


class BadRequest(Exception):
    pass


class NotFound(Exception):
    pass


def validate_theme_name(name: str) -> str:
    name = (name or "").strip()
    if not name or len(name) > MAX_THEME_NAME_LEN or not THEME_NAME_RE.match(name):
        raise BadRequest("invalid theme name %r (must be alphanumeric, dots, dashes, underscores)" % (name,))
    return name


def detect_frontend(configs_path: str) -> str:
    """Returns 'attract-mode' or 'emulationstation' based on config folders."""
    attract_dir = os.path.join(configs_path, "all", "attractmode")
    es_dir = os.path.join(configs_path, "all", "emulationstation")
    if os.path.isdir(attract_dir):
        return "attract-mode"
    if os.path.isdir(es_dir):
        return "emulationstation"
    # Default to emulationstation if neither exists yet
    return "emulationstation"


def themes_directory(configs_path: str, frontend: Optional[str] = None) -> str:
    fe = frontend or detect_frontend(configs_path)
    if fe == "attract-mode":
        return os.path.join(configs_path, "all", "attractmode", "layouts")
    return os.path.join(configs_path, "all", "emulationstation", "themes")


def list_installed_themes(configs_path: str, frontend: Optional[str] = None) -> List[str]:
    dest = themes_directory(configs_path, frontend)
    themes = set()
    if os.path.isdir(dest):
        for entry in os.listdir(dest):
            if not entry.startswith(".") and os.path.isdir(os.path.join(dest, entry)):
                themes.add(entry)
    fe = frontend or detect_frontend(configs_path)
    if fe == "emulationstation":
        sys_dir = "/etc/emulationstation/themes"
        if os.path.isdir(sys_dir):
            for entry in os.listdir(sys_dir):
                if not entry.startswith(".") and os.path.isdir(os.path.join(sys_dir, entry)):
                    themes.add(entry)
    return sorted(themes)


def get_active_theme(configs_path: str, frontend: Optional[str] = None) -> Optional[str]:
    fe = frontend or detect_frontend(configs_path)
    if fe == "attract-mode":
        cfg = os.path.join(configs_path, "all", "attractmode", "attract.cfg")
        if not os.path.isfile(cfg):
            return None
        try:
            with open(cfg, "r", encoding="utf-8", errors="replace") as f:
                for line in f:
                    m = re.match(r"^\s*layout\s+([^\s\r\n]+)", line)
                    if m:
                        return m.group(1)
        except OSError:
            return None
        return None
    cfg = os.path.join(configs_path, "all", "emulationstation", "es_settings.cfg")
    if not os.path.isfile(cfg):
        return None
    try:
        with open(cfg, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
            m = re.search(r'<string\s+name="ThemeSet"\s+value="([^"]*)"\s*/>', content)
            if m:
                return m.group(1)
    except OSError:
        return None
    return None


def get_theme_status(configs_path: str) -> dict:
    fe = detect_frontend(configs_path)
    dest = themes_directory(configs_path, fe)
    active = get_active_theme(configs_path, fe)
    installed = list_installed_themes(configs_path, fe)
    return {
        "frontend": fe,
        "activeTheme": active,
        "installedThemes": installed,
        "themesDir": dest,
    }


def activate_theme(configs_path: str, name: str) -> dict:
    theme = validate_theme_name(name)
    fe = detect_frontend(configs_path)
    previous = get_active_theme(configs_path, fe)
    changed = (previous != theme)
    backup_file = None

    if fe == "attract-mode":
        cfg = os.path.join(configs_path, "all", "attractmode", "attract.cfg")
        if not os.path.isfile(cfg):
            os.makedirs(os.path.dirname(cfg), exist_ok=True)
            with open(cfg, "w", encoding="utf-8") as f:
                f.write("# Generated by rinkmasterd\n\ndisplay\tArcade\n\tlayout               %s\n\tromlist              Arcade\n" % (theme,))
            changed = True
        elif changed:
            backup_file = cfg + ".bak-theme"
            shutil.copy2(cfg, backup_file)
            with open(cfg, "r", encoding="utf-8", errors="replace") as f:
                lines = f.readlines()
            new_lines = []
            has_layout = False
            for line in lines:
                if re.match(r"^\s*layout\s+", line):
                    new_lines.append("\tlayout               %s\n" % (theme,))
                    has_layout = True
                else:
                    new_lines.append(line)
            if not has_layout:
                # Add layout under display blocks or at end
                updated = []
                inserted = False
                for line in new_lines:
                    updated.append(line)
                    if line.startswith("display\t") and not inserted:
                        updated.append("\tlayout               %s\n" % (theme,))
                if not inserted:
                    updated.append("\n\tlayout               %s\n" % (theme,))
                new_lines = updated
            tmp = cfg + ".tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                f.writelines(new_lines)
            os.replace(tmp, cfg)
    else:
        cfg = os.path.join(configs_path, "all", "emulationstation", "es_settings.cfg")
        if not os.path.isfile(cfg):
            os.makedirs(os.path.dirname(cfg), exist_ok=True)
            with open(cfg, "w", encoding="utf-8") as f:
                f.write('<?xml version="1.0"?>\n<config>\n  <string name="ThemeSet" value="%s" />\n</config>\n' % (theme,))
            changed = True
        elif changed:
            backup_file = cfg + ".bak-theme"
            shutil.copy2(cfg, backup_file)
            with open(cfg, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
            if '<string name="ThemeSet"' in content:
                content = re.sub(r'<string\s+name="ThemeSet"\s+value="[^"]*"\s*/>',
                                 '<string name="ThemeSet" value="%s" />' % (theme,), content)
            elif '</config>' in content:
                content = content.replace('</config>', '  <string name="ThemeSet" value="%s" />\n</config>' % (theme,))
            else:
                content += '\n<string name="ThemeSet" value="%s" />\n' % (theme,)
            tmp = cfg + ".tmp"
            with open(tmp, "w", encoding="utf-8") as f:
                f.write(content)
            os.replace(tmp, cfg)

    return {
        "frontend": fe,
        "theme": theme,
        "activeTheme": theme,
        "previousTheme": previous,
        "changed": changed,
        "backup": backup_file,
    }


def _safe_extract_tar(tf: tarfile.TarFile, dest_dir: str) -> List[str]:
    extracted = []
    dest_dir = os.path.abspath(dest_dir)
    for member in tf.getmembers():
        target = os.path.abspath(os.path.join(dest_dir, member.name))
        if not target.startswith(dest_dir + os.sep) and target != dest_dir:
            raise BadRequest("archive entry %r escapes destination directory" % (member.name,))
        if member.isdir():
            os.makedirs(target, exist_ok=True)
        elif member.isreg():
            os.makedirs(os.path.dirname(target), exist_ok=True)
            fsrc = tf.extractfile(member)
            if fsrc:
                with open(target, "wb") as fdst:
                    shutil.copyfileobj(fsrc, fdst)
                os.chmod(target, 0o644)
                extracted.append(member.name)
    return extracted


def _safe_extract_zip(zf: zipfile.ZipFile, dest_dir: str) -> List[str]:
    extracted = []
    dest_dir = os.path.abspath(dest_dir)
    for info in zf.infolist():
        target = os.path.abspath(os.path.join(dest_dir, info.filename))
        if not target.startswith(dest_dir + os.sep) and target != dest_dir:
            raise BadRequest("archive entry %r escapes destination directory" % (info.filename,))
        if info.is_dir():
            os.makedirs(target, exist_ok=True)
        else:
            os.makedirs(os.path.dirname(target), exist_ok=True)
            with zf.open(info) as fsrc, open(target, "wb") as fdst:
                shutil.copyfileobj(fsrc, fdst)
            os.chmod(target, 0o644)
            extracted.append(info.filename)
    return extracted


def install_theme_archive(configs_path: str, name: str, archive_bytes: bytes,
                          activate: bool = True) -> dict:
    if len(archive_bytes) > MAX_ARCHIVE_BYTES:
        raise BadRequest("archive exceeds maximum size (%d bytes)" % (MAX_ARCHIVE_BYTES,))
    theme = validate_theme_name(name)
    fe = detect_frontend(configs_path)
    dest_dir = os.path.join(themes_directory(configs_path, fe), theme)
    os.makedirs(dest_dir, exist_ok=True)

    extracted_files: List[str] = []
    # Try tar / tar.gz first
    try:
        with tarfile.open(fileobj=io.BytesIO(archive_bytes)) as tf:
            extracted_files = _safe_extract_tar(tf, dest_dir)
    except tarfile.TarError:
        # Try zip
        try:
            with zipfile.ZipFile(io.BytesIO(archive_bytes)) as zf:
                extracted_files = _safe_extract_zip(zf, dest_dir)
        except zipfile.BadZipFile:
            raise BadRequest("could not unpack archive as tar or zip")

    activated = False
    backup = None
    if activate:
        act = activate_theme(configs_path, theme)
        activated = True
        backup = act.get("backup")

    return {
        "frontend": fe,
        "theme": theme,
        "destDir": dest_dir,
        "files": extracted_files,
        "activated": activated,
        "backup": backup,
    }
